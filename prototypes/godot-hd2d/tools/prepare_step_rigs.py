def prepare():
 result = {}
 for name, rows in RIGS.items():
  source = ROOT/'assets/characters'/f'{name}-walk.png'
  mask = Image.new('RGBA', (256,768))
  records = []
  original=Image.open(source).convert("RGBA")
  for row, legs in enumerate(rows):
   layers=[]
   for hip, foot, polygon in legs:
    layer=Image.new('L',(256,256));ImageDraw.Draw(layer).polygon(polygon,fill=255)
    # Der Ansatz bleibt mit der Huefte verbunden; kein harter ausgeschnittener Rand.
    if name=='starlet':
     crop=original.crop((0,row*256,256,(row+1)*256))
     gold=Image.new('L',(256,256))
     gold.putdata([255 if r>b*1.15 and g>b*1.10 else 0 for r,g,b,a in crop.get_flattened_data()])
     from PIL import ImageChops
     layer=ImageChops.multiply(layer,gold)
    layer=layer.filter(ImageFilter.GaussianBlur(.6))
    layers.append(layer)
   while len(layers)<4:layers.append(Image.new('L',(256,256)))
   frame=Image.merge('RGBA',tuple(layers))
   mask.paste(frame,(0,row*256))
   feet=[p[1] for p in legs]
   if name=='starlet':
    feet=[]
    art=original.crop((0,row*256,256,(row+1)*256))
    for channel in layers[:2]:
     pixels=[(x,y) for y in range(256) for x in range(256) if channel.getpixel((x,y))>200 and art.getpixel((x,y))[3]>128]
     bottom=max(y for x,y in pixels)
     tips=[x for x,y in pixels if y==bottom]
     feet.append([sum(tips)/len(tips),bottom])
   records.append({'hips':[p[0] for p in legs],'feet':feet, 'ground':max(p[1] for p in feet)})
  raw=mask.tobytes()
  result[name]={'rows':records,'half_stride':AMPLITUDES[name], 'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
                'mask':base64.b64encode(zlib.compress(raw,9)).decode(), 'mask_sha256':hashlib.sha256(raw).hexdigest()}
 mask=Image.new('RGBA',(256,768))
 for row, wings in enumerate(FLIGHT):
  channels=[]
  for pivot, polygon in wings:
   layer=Image.new('L',(256,256));ImageDraw.Draw(layer).polygon(polygon,fill=255)
   layer=layer.filter(ImageFilter.GaussianBlur(8.0))
   hold=Image.new('L',(256,256));draw=ImageDraw.Draw(hold)
   boxes=([(95,0,224,155),(110,125,255,255)] if row==0 else
          [(70,0,114,123),(144,0,190,123),(91,111,167,255)] if row==1 else
          [(84,0,179,103),(101,80,163,255)])
   for box in boxes:draw.rectangle(box,fill=255)
   from PIL import ImageChops
   layer=ImageChops.multiply(layer,ImageChops.invert(hold.filter(ImageFilter.GaussianBlur(5.0))))
   channels.append(layer)
  mask.paste(Image.merge('RGBA',(channels[0],channels[1],Image.new('L',(256,256)),Image.new('L',(256,256)))),(0,row*256))
 raw=mask.tobytes()
 result['nocti']['flight']={'pivots':[[wing[0] for wing in row] for row in FLIGHT],
    'mask':base64.b64encode(zlib.compress(raw,9)).decode(),
    'source_sha256':hashlib.sha256((ROOT/'assets/characters/nocti-flight.png').read_bytes()).hexdigest()}
 return result

